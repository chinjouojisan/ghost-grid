// Ghost Grid — service worker
//
// Strategy: cache-first for the app shell, so it opens instantly and works
// offline once installed. CACHE_VERSION is the only thing that needs bumping
// when index.html changes (new draw data, new features) — bumping it makes
// every client fetch fresh copies on next launch and discard the old cache.
const CACHE_VERSION = 'ghost-grid-v1';
const APP_SHELL = [
  './',
  './index.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_VERSION).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_VERSION).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((response) => {
          if (response && response.status === 200) {
            const copy = response.clone();
            caches.open(CACHE_VERSION).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => cached); // offline: fall back to whatever is cached
      // cache-first: serve immediately if we have it, refresh in the background
      return cached || network;
    })
  );
});
